-- Estrutura inicial do banco, igual às entidades JPA atuais.
-- Daqui pra frente, qualquer mudança no banco vira um novo arquivo V2__..., V3__... (nunca editar este).

CREATE TABLE IF NOT EXISTS aluno (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255),
    cpf   VARCHAR(255),
    email VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS professores (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255),
    email VARCHAR(255),
    cpf   VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS disciplinas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255),
    professor_id BIGINT REFERENCES professores (id)
);

CREATE TABLE IF NOT EXISTS matricula_aluno (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota1         DOUBLE PRECISION,
    nota2         DOUBLE PRECISION,
    aluno_id      BIGINT REFERENCES aluno (id),
    disciplina_id BIGINT REFERENCES disciplinas (id),
    status        VARCHAR(255)
);
